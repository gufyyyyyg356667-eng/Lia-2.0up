// Signing values come from keystore.properties (git-ignored). Missing file = unsigned release.
// Direct-build licensing endpoint. Read from git-ignored license.properties; never hardcoded.
val licenseProps = Properties().apply {
    val f = rootProject.file("license.properties")
    if (f.exists()) f.inputStream().use { load(it) }
}

val keystoreProps = Properties().apply {
    val f = rootProject.file("keystore.properties")
    if (f.exists()) f.inputStream().use { load(it) }
}

android {
    namespace = "com.Lia.assistant"
    compileSdk = 36

    defaultConfig {
        applicationId = "com.Lia.assistant"
        minSdk = 26
        targetSdk = 36
        versionCode = 1
        versionName = "1.0.0"
    }

    signingConfigs {
        create("release") {
            if (keystoreProps.containsKey("storeFile")) {
                storeFile = rootProject.file(keystoreProps.getProperty("storeFile"))
                storePassword = keystoreProps.getProperty("storePassword")
                keyAlias = keystoreProps.getProperty("keyAlias")
                keyPassword = keystoreProps.getProperty("keyPassword")
            }
        }
    }

    flavorDimensions += "distribution"
    productFlavors {
        // Both flavors share the same code today. Accessibility-based features (Part 07/12)
        // must go only into src/direct when they are added.
        create("direct") {
            dimension = "distribution"
            applicationIdSuffix = ".direct"
            buildConfigField(
                "String",
                "LICENSE_BASE_URL",
                "\"${licenseProps.getProperty("licenseBaseUrl", "").trim()}\"",
            )
        }
        create("play") {
            dimension = "distribution"
        }
    }

    buildTypes {
        release {
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
            if (keystoreProps.containsKey("storeFile")) {
                signingConfig = signingConfigs.getByName("release")
            }
        }
    }

    buildFeatures {
        compose = true
        buildConfig = true
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    testOptions {
        unitTests.isReturnDefaultValues = true
    }
}

